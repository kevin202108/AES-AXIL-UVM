static uint8_t xtime(uint8_t b)
{
    uint8_t x = (uint8_t)(b << 1);
    if (b & 0x80u)
        x ^= 0x1bu;
    return x;
}

static uint8_t gmul(uint8_t a, uint8_t b)
{
    uint8_t p = 0;
    int i;
    for (i = 0; i < 8; i++) {
        if (b & 1u)
            p ^= a;
        a = xtime(a);
        b >>= 1;
    }
    return p;
}

static void key_expand(const uint8_t key[16], uint8_t rk[176])
{
    uint8_t temp[4];
    uint8_t t0;
    uint8_t rcon = 0x01;
    int i, j;

    memcpy(rk, key, 16);
    i = 16;
    while (i < 176) {
        for (j = 0; j < 4; j++)
            temp[j] = rk[i - 4 + j];
        if ((i % 16) == 0) {
            t0 = temp[0];
            temp[0] = temp[1];
            temp[1] = temp[2];
            temp[2] = temp[3];
            temp[3] = t0;
            for (j = 0; j < 4; j++)
                temp[j] = sbox[temp[j]];
            temp[0] ^= rcon;
            rcon = xtime(rcon);
        }
        for (j = 0; j < 4; j++)
            rk[i + j] = (uint8_t)(rk[i - 16 + j] ^ temp[j]);
        i += 4;
    }
}

static void add_round_key(uint8_t s[16], const uint8_t rk[176], int round)
{
    int i;
    for (i = 0; i < 16; i++)
        s[i] ^= rk[round * 16 + i];
}

static void sub_bytes(uint8_t s[16])
{
    int i;
    for (i = 0; i < 16; i++)
        s[i] = sbox[s[i]];
}

/* column-major: index = row + 4*col */
static void shift_rows(uint8_t s[16])
{
    uint8_t t[16];
    int r, c;
    for (r = 0; r < 4; r++)
        for (c = 0; c < 4; c++)
            t[r + 4 * c] = s[r + 4 * ((c + r) % 4)];
    memcpy(s, t, 16);
}

static void mix_columns(uint8_t s[16])
{
    int c;
    for (c = 0; c < 4; c++) {
        uint8_t s0 = s[4 * c];
        uint8_t s1 = s[4 * c + 1];
        uint8_t s2 = s[4 * c + 2];
        uint8_t s3 = s[4 * c + 3];
        s[4 * c]     = (uint8_t)(gmul(0x02, s0) ^ gmul(0x03, s1) ^ s2 ^ s3);
        s[4 * c + 1] = (uint8_t)(s0 ^ gmul(0x02, s1) ^ gmul(0x03, s2) ^ s3);
        s[4 * c + 2] = (uint8_t)(s0 ^ s1 ^ gmul(0x02, s2) ^ gmul(0x03, s3));
        s[4 * c + 3] = (uint8_t)(gmul(0x03, s0) ^ s1 ^ s2 ^ gmul(0x02, s3));
    }
}

void aes128_encrypt(const uint8_t key[16],
                    const uint8_t pt[16],
                    uint8_t       ct[16])
{
    uint8_t s[16];
    uint8_t rk[176];
    int round;

    key_expand(key, rk);
    memcpy(s, pt, 16);
    add_round_key(s, rk, 0);
    for (round = 1; round <= 9; round++) {
        sub_bytes(s);
        shift_rows(s);
        mix_columns(s);
        add_round_key(s, rk, round);
    }
    sub_bytes(s);
    shift_rows(s);
    add_round_key(s, rk, 10);
    memcpy(ct, s, 16);
}

int aes128_selfcheck(void)
{
    /* FIPS-197 Appendix C.1 */
    static const uint8_t key_fips[16] = {
        0x00,0x01,0x02,0x03,0x04,0x05,0x06,0x07,
        0x08,0x09,0x0a,0x0b,0x0c,0x0d,0x0e,0x0f
    };
    static const uint8_t pt_fips[16] = {
        0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,
        0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff
    };
    static const uint8_t ct_fips[16] = {
        0x69,0xc4,0xe0,0xd8,0x6a,0x7b,0x04,0x30,
        0xd8,0xcd,0xb7,0x80,0x70,0xb4,0xc5,0x5a
    };
    /* all-zero key and plaintext */
    static const uint8_t zero[16] = {0};
    static const uint8_t ct_zero[16] = {
        0x66,0xe9,0x4b,0xd4,0xef,0x8a,0x2c,0x3b,
        0x88,0x4c,0xfa,0x59,0xca,0x34,0x2b,0x2e
    };
    uint8_t out[16];

    aes128_encrypt(key_fips, pt_fips, out);
    if (memcmp(out, ct_fips, 16) != 0)
        return 1;
    aes128_encrypt(zero, zero, out);
    if (memcmp(out, ct_zero, 16) != 0)
        return 2;
    return 0;
}
